// Generates: sql/004_seed_data.sql  and  js/data/exercises.generated.js
// Run:  node tools/build-seed.mjs
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { EXERCISES } from './exercises.source.mjs';

const NS = 'performance-lab:exercise:';
const idFor = (slug) => {          // deterministic UUID-shaped id so the app and DB always agree
  const h = createHash('sha1').update(NS + slug).digest('hex');
  return `${h.slice(0,8)}-${h.slice(8,12)}-5${h.slice(13,16)}-a${h.slice(17,20)}-${h.slice(20,32)}`;
};
const trackingFor = (type) => ({
  weight_reps: { weight: true, reps: true },
  bodyweight_reps: { reps: true, added_weight: true },
  assisted: { reps: true, assistance: true },
  cardio: { duration: true, distance: true, speed: true, incline: true, heart_rate: true },
  isometric: { duration: true },
  mobility: { duration: true, reps: true },
}[type]);

const rows = EXERCISES.map(([slug,name,aliases,primary,secondary,equipment,type,pattern,instructions,mistakes]) => ({
  id: idFor(slug), slug, name, aliases, primary_muscles: primary, secondary_muscles: secondary,
  equipment, exercise_type: type, movement_pattern: pattern, tracking_config: trackingFor(type),
  instructions, common_mistakes: mistakes, is_system: true,
}));

const q = (s) => s == null ? 'null' : `'${String(s).replace(/'/g, "''")}'`;
const arr = (a) => `array[${a.map(q).join(',')}]::text[]`;
const sql = [
  '-- Performance Lab — 004 starter exercise library (generated by tools/build-seed.mjs)',
  '-- Safe to re-run: existing rows are updated, nothing else is touched.',
  'insert into public.exercises (id, name, aliases, primary_muscles, secondary_muscles, equipment, movement_pattern, exercise_type, tracking_config, instructions, common_mistakes, is_system) values',
  rows.map(r => `(${q(r.id)}, ${q(r.name)}, ${arr(r.aliases)}, ${arr(r.primary_muscles)}, ${arr(r.secondary_muscles)}, ${arr(r.equipment)}, ${q(r.movement_pattern)}, ${q(r.exercise_type)}, ${q(JSON.stringify(r.tracking_config))}::jsonb, ${q(r.instructions)}, ${q(r.common_mistakes)}, true)`).join(',\n'),
  'on conflict (id) do update set name = excluded.name, aliases = excluded.aliases, primary_muscles = excluded.primary_muscles,',
  '  secondary_muscles = excluded.secondary_muscles, equipment = excluded.equipment, movement_pattern = excluded.movement_pattern,',
  '  exercise_type = excluded.exercise_type, tracking_config = excluded.tracking_config, instructions = excluded.instructions,',
  '  common_mistakes = excluded.common_mistakes;',
  '',
].join('\n');
writeFileSync(new URL('../sql/004_seed_data.sql', import.meta.url), sql);

const js = `// GENERATED by tools/build-seed.mjs — do not edit by hand.\nexport const SYSTEM_EXERCISES = ${JSON.stringify(rows, null, 1)};\n`;
writeFileSync(new URL('../js/data/exercises.generated.js', import.meta.url), js);
console.log(`Generated ${rows.length} exercises.`);
